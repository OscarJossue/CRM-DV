class NotificationViewSet(TenantModelViewSet):
    module_name = "notifications"
    queryset = Notification.objects.select_related(
        "id_user",
        "id_user__id_company",
        "id_user__id_role",
    ).all()
    serializer_class = NotificationSerializer
    tenant_filter_path = None
    tenant_create_field = None

    def get_queryset(self):
        return notification_list_for_user(self.request.user)

    def perform_create(self, serializer):
        target_user = serializer.validated_data.get("id_user")

        if not self.request.user.is_superuser:
            if not target_user or target_user.id_company_id != self.request.user.id_company_id:
                raise PermissionDenied("You can only create notifications for users in your company.")

        serializer.save()

    def perform_update(self, serializer):
        target_user = serializer.validated_data.get("id_user")

        if not self.request.user.is_superuser:
            if target_user and target_user.id_company_id != self.request.user.id_company_id:
                raise PermissionDenied("You can only update notifications for users in your company.")

        serializer.save()