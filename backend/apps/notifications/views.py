def get_notification_company_slug(request=None, kwargs=None):
    kwargs = kwargs or {}

    if kwargs.get("company_slug"):
        return kwargs.get("company_slug")

    current_company = getattr(request, "current_company", None) if request else None

    if current_company and getattr(current_company, "slug", None):
        return current_company.slug

    user = getattr(request, "user", None) if request else None
    user_company = getattr(user, "id_company", None) if user else None

    if user_company and getattr(user_company, "slug", None):
        return user_company.slug

    return None


def notification_reverse(name, request=None, kwargs=None, **extra_kwargs):
    url_kwargs = {}
    company_slug = get_notification_company_slug(request=request, kwargs=kwargs)

    if company_slug:
        url_kwargs["company_slug"] = company_slug

    url_kwargs.update(extra_kwargs)

    try:
        return reverse(f"notifications:{name}", kwargs=url_kwargs)
    except NoReverseMatch:
        url_kwargs.pop("company_slug", None)
        return reverse(f"notifications:{name}", kwargs=url_kwargs)


class NotificationListView(LoginRequiredMixin, ModulePermissionRequiredMixin, ListView):
    module_name = "notifications"
    permission_required = PERMISSION_VIEW
    template_name = "notifications/list.html"
    context_object_name = "notifications"
    paginate_by = 20
    login_url = "/login/"

    def get_queryset(self):
        return notification_list_for_user(self.request.user)

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)

        context["page_title"] = "Notifications"
        context["company_slug"] = get_notification_company_slug(
            request=self.request,
            kwargs=self.kwargs,
        )

        context["can_view_notifications"] = user_can_module_action(
            self.request.user,
            "notifications",
            PERMISSION_VIEW,
        )

        # Company users should not manually create or edit notifications.
        # Notifications are generated by platform workflows.
        context["can_create_notifications"] = False
        context["can_edit_notifications"] = False

        return context


class NotificationDetailView(LoginRequiredMixin, ModulePermissionRequiredMixin, DetailView):
    module_name = "notifications"
    permission_required = PERMISSION_VIEW
    model = Notification
    template_name = "notifications/detail.html"
    context_object_name = "notification"
    pk_url_kwarg = "id_notification"
    login_url = "/login/"

    def get_queryset(self):
        return notification_list_for_user(self.request.user)

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)

        company_slug = get_notification_company_slug(
            request=self.request,
            kwargs=self.kwargs,
        )

        context["page_title"] = "Notification Details"
        context["company_slug"] = company_slug

        context["notification_list_url"] = notification_reverse(
            "notification_list",
            request=self.request,
            kwargs=self.kwargs,
        )

        context["notification_mark_read_url"] = notification_reverse(
            "notification_mark_read",
            request=self.request,
            kwargs=self.kwargs,
            id_notification=self.object.id_notification,
        )

        context["notification_mark_unread_url"] = notification_reverse(
            "notification_mark_unread",
            request=self.request,
            kwargs=self.kwargs,
            id_notification=self.object.id_notification,
        )

        context["notification_archive_url"] = notification_reverse(
            "notification_archive",
            request=self.request,
            kwargs=self.kwargs,
            id_notification=self.object.id_notification,
        )

        return context


