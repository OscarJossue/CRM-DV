@require_POST
def notification_mark_all_read_view(request, company_slug=None):
    updated_count = mark_all_user_notifications_read(request.user)

    if updated_count:
        messages.success(request, f"{updated_count} notification(s) marked as read.")
    else:
        messages.info(request, "No unread notifications found.")

    return redirect(
        notification_reverse(
            "notification_list",
            request=request,
            kwargs={"company_slug": company_slug},
        )
    )

@require_POST
def notification_mark_read_view(request, id_notification, company_slug=None):
    notification = get_object_or_404(
        notification_list_for_user(request.user),
        id_notification=id_notification,
    )

    if not user_can_access_notification(request.user, notification):
        return HttpResponseForbidden("Permission denied.")

    notification_mark_read(notification)
    messages.success(request, "Notification marked as read.")

    return redirect(
        notification_reverse(
            "notification_detail",
            request=request,
            kwargs={"company_slug": company_slug},
            id_notification=notification.id_notification,
        )
    )


