    def perform_create(self, serializer):
        payment = serializer.save()

        if (
            not self.request.user.is_superuser
            and payment.id_company_id
            and payment.id_company_id != self.request.user.id_company_id
        ):
            raise PermissionDenied("You can only create payments for your company.")

        try:
            register_payment(
                payment=payment,
                user=self.request.user,
                allow_overpayment=True,
            )
            refresh_payment_related_invoices(payment)
        except Exception as error:
            raise PermissionDenied(str(error))

    def perform_update(self, serializer):
        payment = self.get_object()

        if not user_can_access_payment(self.request.user, payment):
            raise PermissionDenied("You can only update payments from your company.")

        instance = serializer.save()
        refresh_payment_related_invoices(instance)

