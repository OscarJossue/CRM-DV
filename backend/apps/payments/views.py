def payment_void_view(request, id_payment, company_slug=None):
    permission_response = require_module_action_or_403(
        request.user,
        "payments",
        PERMISSION_APPROVE,
    )

    if permission_response:
        return permission_response

    payment = get_object_or_404(payment_list_for_user(request.user), id_payment=id_payment)

    if not user_can_access_payment(request.user, payment):
        return HttpResponseForbidden("Permission denied.")

    if request.method == "GET":
        messages.error(request, "Please use the Void button and enter the void reason.")
        return redirect("payments:payment_detail", id_payment=payment.id_payment)

    if request.method != "POST":
        return HttpResponseForbidden("Invalid request method.")

    reason = request.POST.get("void_reason", "").strip()

    try:
        payment_void(
            payment=payment,
            user=request.user,
            reason=reason,
        )

        refresh_payment_related_invoices(payment)
        payment.refresh_from_db()

        messages.success(request, "Payment voided successfully.")

        return redirect("payments:payment_list")

    except Exception as error:
        messages.error(request, f"Payment could not be voided: {error}")
        return redirect("payments:payment_detail", id_payment=payment.id_payment)


@require_POST
def apply_credit_to_invoice_view(request, id_invoice, company_slug=None):
    permission_response = require_module_action_or_403(
        request.user,
        "payments",
        PERMISSION_CREATE,
    )

    if permission_response:
        return permission_response

    invoice = get_object_or_404(
        invoice_queryset_for_user(request.user),
        id_invoice=id_invoice,
    )

    recalculate_invoice_payment_status(invoice)
    invoice.refresh_from_db()

    amount = request.POST.get("credit_amount", "").strip()

    try:
        apply_client_credit_to_invoice(
            company=invoice.id_company,
            client=invoice.id_client,
            invoice=invoice,
            amount=amount,
            user=request.user,
        )

        recalculate_invoice_payment_status(invoice)

        messages.success(
            request,
            f"Credit balance applied successfully to invoice {invoice.invoice_number or invoice.id_invoice}.",
        )

    except Exception as error:
        messages.error(
            request,
            f"Credit balance could not be applied: {error}",
        )

    return redirect(
        "invoices:invoice_detail",
        id_invoice=invoice.id_invoice,
    )


