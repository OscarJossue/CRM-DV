def get_finance_company_for_user(user):
    if not user or not user.is_authenticated:
        return None

    company = getattr(user, "id_company", None)

    if company:
        return company

    if user.is_superuser:
        try:
            from apps.companies.models import Company

            return Company.objects.first()
        except Exception:
            return None

    return None


class FinanceClientListView(LoginRequiredMixin, ModulePermissionRequiredMixin, TemplateView):
    module_name = "payments"
    permission_required = PERMISSION_VIEW
    template_name = "payments/finance_clients.html"
    login_url = "/login/"

    def dispatch(self, request, *args, **kwargs):
        self.company = get_finance_company_for_user(request.user)

        if not self.company:
            messages.error(
                request,
                "Your user does not have a company assigned. Please assign a company before using finance.",
            )
            return redirect("payments:payment_list")

        return super().dispatch(request, *args, **kwargs)

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)

        summaries = get_all_clients_financial_summaries(self.company)

        total_invoiced = 0
        total_paid = 0
        total_allocated = 0
        total_balance_due = 0
        total_credit_balance = 0
        total_open_invoices = 0

        for summary in summaries:
            total_invoiced += summary["total_invoiced"]
            total_paid += summary["total_paid"]
            total_allocated += summary.get("total_allocated", 0)
            total_balance_due += summary["balance_due"]
            total_credit_balance += summary["credit_balance"]
            total_open_invoices += summary["open_invoices"]

        context["page_title"] = "Financial Summary by Client"
        context["summaries"] = summaries
        context["total_invoiced"] = total_invoiced
        context["total_paid"] = total_paid
        context["total_allocated"] = total_allocated
        context["total_balance_due"] = total_balance_due
        context["total_credit_balance"] = total_credit_balance
        context["total_open_invoices"] = total_open_invoices

        return context


